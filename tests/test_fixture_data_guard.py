def test_ensure_splits_preserves_existing_complete_splits(tmp_path) -> None:
    pool = tmp_path / "real_pool.jsonl"
    # Pool rows all use the training role; split files use the per-split role.
    pool_row_train = _base_row(example_id="train-1")
    pool_row_val = _base_row(example_id="val-1")
    pool_row_test = _base_row(example_id="test-1")
    _write_pool(pool, [pool_row_train, pool_row_val, pool_row_test])
    train_row = dict(pool_row_train)
    train_row["data_role"] = "training"
    val_row = dict(pool_row_val)
    val_row["data_role"] = "validation"
    test_row = dict(pool_row_test)
    test_row["data_role"] = "test"
    splits = tmp_path / "splits"
    splits.mkdir()
    _write_pool(splits / "train.jsonl", [train_row])
    (splits / "train_ids.json").write_text(
        json.dumps(["train-1"]) + "\n", encoding="utf-8"
    )
    _write_pool(splits / "validation.jsonl", [val_row])
    (splits / "validation_ids.json").write_text(
        json.dumps(["val-1"]) + "\n", encoding="utf-8"
    )
