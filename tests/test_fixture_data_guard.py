# --- Pool / split provenance consistency --------------------------------------


def test_existing_splits_from_different_pool_are_rejected(tmp_path) -> None:
    real_pool = tmp_path / "real_pool.jsonl"
    _write_pool(real_pool, [_base_row(example_id="real-row-1")])

    # Simulate a stale split directory that was generated from a different
    # pool (e.g. an older smoke-fixture pool).
    stale_pool = tmp_path / "stale_pool.jsonl"
    _write_pool(stale_pool, [_fixture_row(example_id="stale-row-1")])

    splits = tmp_path / "splits"
    _write_split_dir(
        splits,
        [_fixture_row(example_id="stale-row-1")],
        [_fixture_row(example_id="stale-row-2")],
        [_fixture_row(example_id="stale-row-3")],
        pool_path=stale_pool,
    )

    # The pool has changed; the splits on disk no longer match it.
    with pytest.raises(ValueError, match="different training pool"):
        ensure_splits(split_dir=splits, pool_path=real_pool)


def test_existing_splits_with_missing_manifest_are_rejected(tmp_path) -> None:
    pool = tmp_path / "real_pool.jsonl"
    _write_pool(pool, [_base_row(example_id="real-1")])
    splits = tmp_path / "splits"
    splits.mkdir()
    _write_pool(splits / "train.jsonl", [_base_row(example_id="train-1", data_role="training")])
    (splits / "train_ids.json").write_text(
        json.dumps(["train-1"]) + "\n", encoding="utf-8"
    )
    _write_pool(splits / "validation.jsonl", [_base_row(example_id="val-1", data_role="validation")])
    (splits / "validation_ids.json").write_text(
        json.dumps(["val-1"]) + "\n", encoding="utf-8"
    )
    _write_pool(splits / "test.jsonl", [_base_row(example_id="test-1", data_role="test")])
    (splits / "test_ids.json").write_text(
        json.dumps(["test-1"]) + "\n", encoding="utf-8"
    )
    # No split_manifest.json was written.

    with pytest.raises(FileNotFoundError, match="split_manifest.json"):
        ensure_splits(split_dir=splits, pool_path=pool)


