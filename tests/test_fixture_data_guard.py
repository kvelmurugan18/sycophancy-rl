def test_existing_valid_splits_are_preserved_with_matching_manifest(tmp_path) -> None:
    pool = tmp_path / "real_pool.jsonl"
    # The pool only holds "training"-role rows by design; split files hold
    # the per-split roles.
    pool_row_1 = _base_row(example_id="real-1")
    pool_row_2 = _base_row(example_id="real-2")
    pool_row_3 = _base_row(example_id="real-3")
    _write_pool(pool, [pool_row_1, pool_row_2, pool_row_3])
    train_row = dict(pool_row_1)
    train_row["data_role"] = "training"
    val_row = dict(pool_row_2)
    val_row["data_role"] = "validation"
    test_row = dict(pool_row_3)
    test_row["data_role"] = "test"
    splits = tmp_path / "splits"
    _write_split_dir(splits, [train_row], [val_row], [test_row], pool_path=pool)

    message = ensure_splits(split_dir=splits, pool_path=pool)

    assert "preserved" in message
    # Manifest and ids on disk match the freshly observed pool SHA.
    current_sha = hashlib.sha256(pool.read_bytes()).hexdigest()
    manifest = json.loads((splits / "split_manifest.json").read_text(encoding="utf-8"))
    assert manifest["source_sha256"] == current_sha


