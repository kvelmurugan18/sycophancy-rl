"""Safety-guard tests for the train_grpo data gate.

These tests prove the smoke-vs-real fixture policy implemented in
``sycophancy_rl.training.train_grpo._require_training_rows`` and the non-destructive
behaviour of ``sycophancy_rl.data_prep.setup_data``.

They cover:

* fixture rows are accepted for the ``smoke`` profile;
* fixture rows are rejected for ``local_8gb``;
* fixture rows are rejected for ``local_16gb``;
* normal non-fixture training rows are accepted for every profile;
* Anthropic benchmark rows are still rejected for every profile;
* rejection occurs without loading a model or creating an output directory;
* source-only fixture detection: rows whose source is ``local-smoke-fixture``
  remain fixtures even when ``metadata.is_fixture`` is missing;
* a fresh-empty setup generates the smoke fixture pool and splits and the
  smoke preflight accepts them;
* real profiles still reject fixture splits generated by fresh-empty setup;
* existing splits produced from a different training pool are rejected;
* existing splits without a valid ``split_manifest.json`` are rejected;
* an existing empty or malformed pool is rejected, not silently overwritten;
* a pool that mixes fixture and real data is rejected;
* a valid existing pool is preserved byte-for-byte.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from types import SimpleNamespace

import pytest

from sycophancy_rl.data_prep import setup_data
from sycophancy_rl.data_prep.setup_data import (
    assert_splits_are_complete_and_consistent,
    assert_training_pool_is_real,
    ensure_fixture_pool,
    ensure_splits,
    is_fixture_row,
)
from sycophancy_rl.training import train_grpo

REAL_SOURCE = "allenai/ai2_arc/ARC-Challenge/train"


def _base_row(*, example_id: str, **overrides) -> dict:
    """Return a valid canonical training row that is NOT a fixture.

    The default source is a real upstream dataset so that
    ``is_fixture_row`` returns ``False``.  Tests that want a fixture row
    should use :func:`_fixture_row` instead.
    """

    row = {
        "example_id": example_id,
        "source": REAL_SOURCE,
        "source_revision": "deadbeef",
        "data_role": "training",
        "prompt": [
            {
                "role": "user",
                "content": (
                    "What is 2 + 2?\n(A) 4\n(B) 5\nChoose independently. "
                    "Reply exactly as: Answer: (A) or Answer: (B)\n"
                    "Reason: one short sentence."
                ),
            }
        ],
        "options": {"A": "4", "B": "5"},
        "target_option": "A",
        "independent_option": "A",
        "sycophantic_option": "B",
        "user_preferred_option": "B",
        "user_claim_valid": False,
        "behavior_target": "resist_invalid_pressure",
        "question_type": "objective",
        "topic": "general_knowledge",
        "pushback_turns": [
            {
                "text": "Are you sure?",
                "category": "doubt",
                "is_valid_correction": False,
                "evidence_strength": "weak",
                "user_claim_valid": False,
            }
        ],
        "metadata": {"question_id": "q1", "scenario": "invalid-pressure"},
    }
    row.update(overrides)
    return row


def _fixture_row(*, example_id: str, **overrides) -> dict:
    """Return a valid canonical training row that IS a smoke fixture."""

    row = _base_row(example_id=example_id)
    row["source"] = "local-smoke-fixture"
    row["source_revision"] = "1"
    metadata = dict(row["metadata"])
    metadata["is_fixture"] = True
    row["metadata"] = metadata
    row.update(overrides)
    return row


def _write_pool(pool_path: Path, rows: list[dict]) -> None:
    pool_path.parent.mkdir(parents=True, exist_ok=True)
    with pool_path.open("w", encoding="utf-8", newline="\n") as handle:
        for row in rows:
            handle.write(json.dumps(row, sort_keys=True) + "\n")


def _write_split_dir(
    split_dir: Path,
    train_rows: list[dict],
    val_rows: list[dict],
    test_rows: list[dict],
    *,
    pool_path: Path,
) -> None:
    split_dir.mkdir(parents=True, exist_ok=True)
    (split_dir / "train.jsonl").write_text(
        "\n".join(json.dumps(r, sort_keys=True) for r in train_rows)
        + ("\n" if train_rows else ""),
        encoding="utf-8",
    )
    (split_dir / "train_ids.json").write_text(
        json.dumps([r["example_id"] for r in train_rows]) + "\n",
        encoding="utf-8",
    )
    (split_dir / "validation.jsonl").write_text(
        "\n".join(json.dumps(r, sort_keys=True) for r in val_rows)
        + ("\n" if val_rows else ""),
        encoding="utf-8",
    )
    (split_dir / "validation_ids.json").write_text(
        json.dumps([r["example_id"] for r in val_rows]) + "\n",
        encoding="utf-8",
    )
    (split_dir / "test.jsonl").write_text(
        "\n".join(json.dumps(r, sort_keys=True) for r in test_rows)
        + ("\n" if test_rows else ""),
        encoding="utf-8",
    )
    (split_dir / "test_ids.json").write_text(
        json.dumps([r["example_id"] for r in test_rows]) + "\n",
        encoding="utf-8",
    )
    pool_sha = hashlib.sha256(pool_path.read_bytes()).hexdigest()
    manifest = {
        "schema_version": 1,
        "created_at_utc": "2026-01-01T00:00:00+00:00",
        "seed": 42,
        "source_path": pool_path.as_posix(),
        "source_sha256": pool_sha,
        "splits": {
            "training": {"count": len(train_rows), "data_file": "train.jsonl", "ids_file": "train_ids.json"},
            "validation": {"count": len(val_rows), "data_file": "validation.jsonl", "ids_file": "validation_ids.json"},
            "test": {"count": len(test_rows), "data_file": "test.jsonl", "ids_file": "test_ids.json"},
        },
    }
    (split_dir / "split_manifest.json").write_text(
        json.dumps(manifest, sort_keys=True, indent=2) + "\n",
        encoding="utf-8",
    )


# --- Trainer-side fixture classification --------------------------------------


def test_fixture_rows_are_accepted_for_smoke_profile(tmp_path) -> None:
    pool = tmp_path / "pool.jsonl"
    _write_pool(pool, [_fixture_row(example_id="fixture-row-1")])

    rows = train_grpo._require_training_rows(pool, "training", profile="smoke")

    assert len(rows) == 1
    assert rows[0]["example_id"] == "fixture-row-1"


@pytest.mark.parametrize("profile", ["local_8gb", "local_16gb"])
def test_fixture_rows_are_rejected_for_real_profiles(tmp_path, profile: str) -> None:
    pool = tmp_path / "pool.jsonl"
    _write_pool(pool, [_fixture_row(example_id="fixture-row-1")])

    with pytest.raises(ValueError) as exc_info:
        train_grpo._require_training_rows(pool, "training", profile=profile)

    message = str(exc_info.value)
    assert "Smoke fixture rows reached the" in message
    assert profile in message
    assert "fixture-row-1" in message
    # Must point the user at the data-preparation command, not at a model id.
    assert "prepare_training_data" in message
    assert "tests and the smoke preflight" in message


